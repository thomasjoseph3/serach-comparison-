/**
 * Scans the query string for known brand aliases.
 * Returns an array of unique matching domains.
 *
 * Example: "Show me Tanishq and CaratLane rings"
 *   → ['tanishq.co.in', 'caratlane.com']
 */
export function detectBrandsInQuery(query) {
    const q = query.toLowerCase();
    const matched = new Set();
    for (const [alias, domain] of BRAND_ALIASES) {
        if (q.includes(alias)) matched.add(domain);
    }
    return [...matched];
}

/**
 * Returns locale-appropriate brand domains for Exa's includeDomains
 * when no specific brand is detected in the query.
 * Capped at 20 — Exa quality degrades with very large domain lists.
 */
export function getExaDomains(gl = 'in') {
    const map = {
        in: INDIAN_BRAND_DOMAINS.slice(0, 20),
        us: US_BRAND_DOMAINS.slice(0, 20),
        gb: US_BRAND_DOMAINS.slice(0, 20),
        jp: JAPAN_BRAND_DOMAINS,
    };
    return map[gl] || INDIAN_BRAND_DOMAINS.slice(0, 20);
}
